// 【内容】& とマスク（filter）で、下位4ビット（右の4つ）だけを取り出す
// 【まずやること】
//   ・そのまま実行して「12」（2進数で 0000 1100）と表示されることを確認する
// 【やってみよう】
//   ① 上位4ビット（左の4つ）だけを取り出すには、filter をどう変える？ 予想してから確かめる
//   ② filter を変えて、一番右のビットだけを取り出す。偶数・奇数の判定に使えるか考える
// ==================================================

#include <stdio.h>

int main(void)
{
    int a = 0b01101100;
    int filter = 0b00001111;

    // 元のコード：下位4ビットを取り出す
    printf("%d\n", a & filter);

    // ① 上位4ビットを取り出す
    filter = 0b11110000;
    printf("%d\n", a & filter);

    // ② 一番右のビットだけを取り出す
    filter = 0b00000001;
    printf("%d\n", a & filter);

    // 偶数・奇数の判定
    if (a & 1) {
        printf("奇数\n");
    } else {
        printf("偶数\n");
    }

    return 0;
}