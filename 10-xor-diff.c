// 【まずやること】
//   ・「/* ここを書き換える */」の行を書き換えて完成させる
//   ・ヒント：一致すると0、違うと1。どの演算の真理値表と同じ？　→排他的論理和
//   ・完成の確認：「5」と表示されればOK
// 【やってみよう】
//   ① c にもう一度 b を同じ演算でかけると、何が出てくる？ printf を追加して確かめる→3
// ==================================================


#include <stdio.h>

int main(void)
{
    int a = 0b00000011;
    int b = 0b00000110;

    int c = a ^ b;

    printf("%d\n", c);  // 5

    // ① c にもう一度 b をXORする
    c = c ^ b;
    printf("%d\n", c);  // 3

    return 0;
}