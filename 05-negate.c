#include <stdio.h>
#include <limits.h>

int main(void)
{
    int num;
    int inverse_num;

    printf("整数=");
    if (scanf("%d", &num) != 1) {
        return 1;
    }

    if (num == INT_MIN) {
        printf("正負逆転した値はintの範囲を超えます。\n");
        return 1;
    }

    inverse_num = ~num + 1;   /* ここを書き換える */

    printf("正負逆転した値は%dです。\n", inverse_num);
    return 0;
}
