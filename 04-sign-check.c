// 【種類】確認（数を入力して実行する）
// 【内容】& で最上位ビットだけを取り出し、入力した数が正の数か負の数かを判定する
// 【まずやること】
//   ・実行して 5 を入力 →「正の数です」、-5 を入力 →「負の数です」と表示されることを確認する
// 【やってみよう】
//   ① 127、-128 を入力して、判定が正しいか確かめる
//   ② 0 を入力すると、どちらと表示される？ 理由を説明してみよう
//   ③ 0b10000000 を 0b00000001 に変えると、何を判定するプログラムになる？
// ==================================================
#include <stdio.h>

int main(void)
{
    signed char d;

    printf("整数=");
    scanf("%hhd", &d);   /* %hhd は1バイトの整数（signed char）を読む書式 */

    if ((d & 0b00000001) == 0) {
        printf("正の数です\n");
    } else {
        printf("負の数です\n");
    }
    return 0;
}

/*
【やってみよう】
 ① 127、-128 を入力して、判定が正しいか確かめる
    127:正の数です
    -128:負の数です
 ② 0 を入力すると、どちらと表示される？ 理由を説明してみよう
    正の数です
    理由：0の符号ビット（左端のビット）が 0 だから。
③ 0b10000000 を 0b00000001 に変えると、何を判定するプログラムになる？
    偶数か奇数かを判定するプログラムになる。
*/