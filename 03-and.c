// 【内容】ビット演算子 & で、2つの数の論理積を1桁ずつ求める
// 【まずやること】
//   ・実行する前に、表示される数を紙で予想する
//   ・実行して、予想が合っていたか確認する（答えはスライドで確認）
// 【やってみよう】
//   ① a と b の値を自由に変えて、ペアの人に結果を予想してもらう
//   ② int c = ~a; に変えると、何が表示される？（ヒント：前回の2の補数）
// ==================================================
#include <stdio.h>

int main(void)
{
    int a = 0b00000011;   /* 10進数で3 */
    int b = 0b00000110;   /* 10進数で6 */
    int c = a ^ b;

    printf("%d\n", c);
    return 0;
}
